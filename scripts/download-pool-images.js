/**
 * Downloads each card image in the seeded game_card_pool to
 * public/data/card-pool/{card_id}.{ext} and emits a SQL migration that
 * repoints the pool rows to those local paths.
 *
 * Usage: node scripts/download-pool-images.js
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, "..");
const outDir = path.join(root, "public", "data", "card-pool");
const seedPath = path.join(root, "supabase", "migrations", "20260417231121_seed_game_card_pool.sql");

const CONCURRENCY = 12;

function extractRows(sql) {
  const re = /^\s*\('([^']+)',\s*'((?:[^']|'')+)',\s*'(https?:\/\/[^']+)'\)/gm;
  return [...sql.matchAll(re)].map((m) => ({
    id: m[1],
    name: m[2].replace(/''/g, "'"),
    url: m[3],
  }));
}

function extFromContentType(ct) {
  if (!ct) return ".jpg";
  if (ct.includes("png")) return ".png";
  if (ct.includes("webp")) return ".webp";
  if (ct.includes("gif")) return ".gif";
  return ".jpg";
}

async function downloadOne(row) {
  // Skip if any extension already exists for this card_id
  const existing = [".jpg", ".png", ".webp"].find((e) =>
    fs.existsSync(path.join(outDir, row.id + e)),
  );
  if (existing) return { ...row, ext: existing, skipped: true };

  const res = await fetch(row.url);
  if (!res.ok) throw new Error(`${row.id}: HTTP ${res.status}`);
  const ext = extFromContentType(res.headers.get("content-type"));
  const buf = Buffer.from(await res.arrayBuffer());
  fs.writeFileSync(path.join(outDir, row.id + ext), buf);
  return { ...row, ext, skipped: false };
}

async function pMap(items, fn, concurrency) {
  const results = new Array(items.length);
  let i = 0;
  let done = 0;
  const workers = Array.from({ length: concurrency }, async () => {
    while (true) {
      const idx = i++;
      if (idx >= items.length) return;
      try {
        results[idx] = await fn(items[idx]);
      } catch (e) {
        results[idx] = { ...items[idx], error: e.message };
      }
      done++;
      if (done % 25 === 0 || done === items.length) {
        console.log(`  ${done}/${items.length}`);
      }
    }
  });
  await Promise.all(workers);
  return results;
}

function escapeSql(s) {
  return String(s).replace(/'/g, "''");
}

async function main() {
  fs.mkdirSync(outDir, { recursive: true });
  const sql = fs.readFileSync(seedPath, "utf8");
  const rows = extractRows(sql);
  console.log(`Found ${rows.length} rows in seed migration`);

  console.log(`Downloading to ${outDir} (concurrency ${CONCURRENCY})...`);
  const results = await pMap(rows, downloadOne, CONCURRENCY);
  const failed = results.filter((r) => r.error);
  const ok = results.filter((r) => !r.error);
  console.log(`Done. ${ok.length} ok, ${failed.length} failed.`);
  if (failed.length) {
    console.log("Failures:");
    failed.slice(0, 10).forEach((f) => console.log(`  ${f.id}: ${f.error}`));
  }

  // Emit SQL migration that updates each row to its local path.
  const ts = new Date()
    .toISOString()
    .replace(/[-:T.Z]/g, "")
    .slice(0, 14);
  const lines = ok
    .map(
      (r) =>
        `UPDATE public.game_card_pool SET image_small = '/data/card-pool/${r.id}${r.ext}' WHERE card_id = '${escapeSql(r.id)}';`,
    )
    .join("\n");
  const migrationSql = `-- Repoint seeded game_card_pool rows to locally-served images\n-- (auto-generated by scripts/download-pool-images.js)\n${lines}\n`;
  const outSql = path.join(
    root,
    "supabase",
    "migrations",
    `${ts}_repoint_game_card_pool_local.sql`,
  );
  fs.writeFileSync(outSql, migrationSql);
  console.log(`Wrote ${outSql} (${migrationSql.length} bytes)`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
